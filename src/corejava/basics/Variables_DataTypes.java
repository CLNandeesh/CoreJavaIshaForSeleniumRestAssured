package corejava.basics;


//Different Data Types in JAVA:
//1. Primitive Data Type: int, char, boolean, float, double, byte, short
//2. Non Primitive Data Type: String, Arrays, List, Set, etc
//Transient and Volatile variables
//Data type: var - stores any type of value and make that as default type for that variable

public class Variables_DataTypes {
    public static void main(String[] args) {
        int a = 100;
        System.out.println(a);

        var v = "Appu";
        System.out.println("v value is " + v.toUpperCase());
    }
}
