package corejava.basics;

public class TypeCasting {
    public static void main(String[] args) {
        byte b=100;
        int i=b; //Low to high
        System.out.println(b+" "+i);

        int a1=1000;
        byte a2=(byte)a1;
        System.out.println(a1+" "+a2);
        System.out.println("***********");
        System.out.println("***********");


    }
}
